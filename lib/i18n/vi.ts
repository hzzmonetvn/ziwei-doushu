const HAN = /[\u3400-\u9FFF]/g;
const entries = Object.entries(VI_TEXT)
  .filter(([key]) => key.length >= 2)
  .sort((a, b) => b[0].length - a[0].length);

/** Chỉ chuyển nội dung hiển thị; không sử dụng hàm này cho khóa dữ liệu, route hoặc phép tính. */
export function translateVisibleText(text: string): string {
  if (!/[\u3400-\u9FFF]/.test(text)) return text;
  const trimmed = text.trim();
  if (!trimmed) return text;
  const full = VI_TEXT[trimmed];
  if (full !== undefined) return text.replace(trimmed, full);
  const originalCount = (trimmed.match(HAN) || []).length;
  // Văn bản dài (kinh điển, trích dẫn, điều khoản) chỉ dịch khi có bản dịch chính xác.
  if (originalCount > 45) return text;
  let translated = trimmed;
  for (const [key, value] of entries) {
    if (translated.includes(key)) translated = translated.split(key).join(value);
  }
  const remain = (translated.match(HAN) || []).length;
  // Tránh tạo câu nửa Hán nửa Việt nếu từ điển chưa bao phủ đủ.
  if (remain > 0 && remain / originalCount > 0.25) return text;
  return text.replace(trimmed, translated);
}
